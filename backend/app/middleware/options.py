from pydantic import BaseModel, ConfigDict, Field
from typing import Dict, Optional, Annotated


# I think we can just do this in the proxy, but in case
class SecurityHeaderOptions(BaseModel):
    """The options for the security header annotated with the purpose
    of each and defaults generated by claude bc i am going to forget the
    syntax and purpose of each"""

    content_security_policy: Annotated[
        Optional[str],
        Field(
            default=None,
            description="Controls which resources can be loaded and executed by the page",
            examples=["default-src 'self'; script-src 'self'"],
            serialization_alias="Content-Security-Policy",
        ),
    ] = None

    strict_transport_security: Annotated[
        Optional[str],
        Field(
            default="max-age=31536000; includeSubDomains",
            description="Forces browsers to use HTTPS for the specified domain",
            examples=[
                "max-age=31536000; includeSubDomains",
                "max-age=63072000; includeSubDomains; preload",
            ],
            serialization_alias="Strict-Transport-Security",
        ),
    ] = "max-age=31536000; includeSubDomains"

    x_content_type_options: Annotated[
        str,
        Field(
            default="nosniff",
            description="Prevents browsers from MIME-sniffing a response away from the declared content type",
            examples=["nosniff"],
            serialization_alias="X-Content-Type-Options",
        ),
    ] = "nosniff"

    x_frame_options: Annotated[
        str,
        Field(
            default="SAMEORIGIN",
            description="Controls whether the browser should allow the page to be rendered in a frame",
            examples=["DENY", "SAMEORIGIN"],
            serialization_alias="X-Frame-Options",
        ),
    ] = "SAMEORIGIN"

    x_xss_protection: Annotated[
        str,
        Field(
            default="1; mode=block",
            description="Enables browser's built-in XSS filter",
            examples=["1; mode=block", "1"],
            serialization_alias="X-XSS-Protection",
        ),
    ] = "1; mode=block"

    referrer_policy: Annotated[
        str,
        Field(
            default="strict-origin-when-cross-origin",
            description="Controls how much referrer information should be included with requests",
            examples=["strict-origin-when-cross-origin", "no-referrer"],
            serialization_alias="Referrer-Policy",
        ),
    ] = "strict-origin-when-cross-origin"

    # permissions_policy: Annotated[
    #     Optional[str],
    #     Field(
    #         default="geolocation=(), camera=(), microphone=()",
    #         description="Controls which browser features and APIs can be used",
    #         examples=["geolocation=(), camera=(), microphone=()",
    #                   "accelerometer=(), camera=(), geolocation=(), gyroscope=(), magnetometer=(), microphone=(), payment=(), usb=()"],
    #         serialization_alias="Permissions-Policy"
    #     )
    # ] = "geolocation=(), camera=(), microphone=()"

    cache_control: Annotated[
        Optional[str],
        Field(
            default="no-store, max-age=0",
            description="Directives for caching mechanisms in both requests and responses",
            examples=["no-store, max-age=0", "no-cache, no-store, must-revalidate"],
            serialization_alias="Cache-Control",
        ),
    ] = "no-store, max-age=0"

    cross_origin_opener_policy: Annotated[
        Optional[str],
        Field(
            default="same-origin",
            description="Controls sharing of browsing context group with cross-origin documents",
            examples=["same-origin", "same-origin-allow-popups"],
            serialization_alias="Cross-Origin-Opener-Policy",
        ),
    ] = "same-origin"

    cross_origin_resource_policy: Annotated[
        Optional[str],
        Field(
            default="same-origin",
            description="Controls if a resource can be loaded by a cross-origin page",
            examples=["same-origin", "same-site", "cross-origin"],
            serialization_alias="Cross-Origin-Resource-Policy",
        ),
    ] = "same-origin"

    cross_origin_embedder_policy: Annotated[
        Optional[str],
        Field(
            default="require-corp",
            description="Controls embedding of cross-origin resources",
            examples=["require-corp", "unsafe-none"],
            serialization_alias="Cross-Origin-Embedder-Policy",
        ),
    ] = "require-corp"

    custom_headers: Annotated[
        Optional[Dict[str, str]],
        Field(
            default=None,
            description="Additional custom headers to include in the response",
            examples=[{"X-API-Version": "1.0.0", "X-Custom-Header": "Value"}],
            exclude=True,
        ),
    ] = None

    model_config = ConfigDict(populate_by_name=True)
